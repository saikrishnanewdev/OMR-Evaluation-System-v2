def find_answer_key_pdf(folder: Path, key_override: Optional[str] = None) -> Optional[Path]:
    """
    Searches the target directory for an Answer Key PDF file.
    Prioritizes filenames containing 'key', 'ans', 'master', 'solution',
    or falls back to the single PDF in the folder.
    """
    if key_override:
        p = Path(key_override).resolve()
        if p.exists() and p.is_file():
            return p
        print(f"[WARNING] Specified key file not found: {key_override}")

    folder = Path(folder).resolve()
    pdf_candidates = [
        f for f in folder.iterdir()
        if f.is_file() and f.suffix.lower() == ".pdf"
    ]
    if not pdf_candidates:
        return None

    # Filter out potential export/result PDFs
    filtered = [
        f for f in pdf_candidates
        if not any(w in f.stem.lower() for w in ("report", "export", "result", "sheet", "summary"))
    ]
    if not filtered:
        filtered = pdf_candidates

    # Check for primary keywords
    for f in filtered:
        name_l = f.stem.lower()
        if any(k in name_l for k in ("key", "ans", "master", "solution", "scheme")):
            return f

    # If only 1 PDF exists, pick it
    return filtered[0]


def find_roster_file(folder: Path, roster_override: Optional[str] = None) -> Optional[Path]:
    """
    Searches the target directory for a Student Roster / Nominal Roll Excel or CSV file.
    Prioritizes filenames containing 'roster', 'nominal', 'student', 'candidate', 'list',
    or falls back to any Excel/CSV in the folder that is not an output report.
    """
    if roster_override:
        p = Path(roster_override).resolve()
        if p.exists() and p.is_file():
            return p
        print(f"[WARNING] Specified roster file not found: {roster_override}")

    folder = Path(folder).resolve()
    candidates = [
        f for f in folder.iterdir()
        if f.is_file() and f.suffix.lower() in (".xlsx", ".xls", ".csv")
        and not f.name.startswith("~$")
    ]
    if not candidates:
        return None

    # Filter out output report files generated by this script
    filtered = [
        f for f in candidates
        if not any(w in f.stem.lower() for w in ("report", "export", "result", "batch_evaluation", "student_identities", "autoevaluated"))
    ]
    if not filtered:
        return None

    # Check for primary keywords
    for f in filtered:
        name_l = f.stem.lower()
        if any(k in name_l for k in ("roster", "nominal", "student", "candidate", "roll", "reg", "enrol")):
            return f

    # If an .xls or .xlsx exists, return the first one
    return filtered[0]


def load_roster(path: Path) -> List[Dict[str, str]]:
    """
    Parses a student roster file into a list of {'roll': ..., 'name': ...} dictionaries.
    Supports Excel 2003 XML (SpreadsheetML), standard Excel (.xlsx/.xls), and CSV.
    """
    path = Path(path).resolve()
    records = []

    # 1. Try Excel 2003 XML (SpreadsheetML)
    try:
        import xml.etree.ElementTree as ET
        tree = ET.parse(path)
        root = tree.getroot()
        ns = {'ss': 'urn:schemas-microsoft-com:office:spreadsheet'}
        rows = root.findall('.//ss:Row', ns)
        if rows:
            for r in rows[1:]:
                cells = [c.find('ss:Data', ns) for c in r.findall('ss:Cell', ns)]
                vals = [c.text.strip() if (c is not None and c.text) else '' for c in cells]
                if not vals or not vals[0]:
                    continue
                # Structure like KNL SA.xls / KNL,SGT.xls:
                # vals[0]: File, vals[1]: Prefix or Name, vals[2]: Roll or Name, vals[3]: Full HT or Name
                if len(vals) > 3 and any(vals[1].startswith(p) for p in ('KNL', 'AMP', 'RJM', 'DSC', 'AP')):
                    records.append({'roll': vals[3].strip(), 'name': ''})
                elif len(vals) > 3 and re.search(r'\d{5}', vals[3]):
                    records.append({'roll': vals[3].strip(), 'name': ''})
                elif len(vals) > 1 and not vals[1].isdigit():
                    records.append({'roll': '', 'name': vals[1].strip()})
            if records:
                return records
    except Exception:
        pass

    # 2. Try standard Pandas read_excel / read_csv
    try:
        if path.suffix.lower() == '.csv':
            df = pd.read_csv(path)
        else:
            try:
                df = pd.read_excel(path)
            except Exception:
                df = pd.read_excel(path, engine='openpyxl')

        # Detect roll and name columns. A daily-test (20Q) roster
        # has no hall ticket: it has 'B No' (batch) and 'ID No'
        # columns instead, kept as 'bno' / 'idno' on the record.
        roll_col = None
        name_col = None
        bno_col = None
        idno_col = None
        for col in df.columns:
            c_l = str(col).lower()
            if not roll_col and any(k in c_l for k in ('roll', 'hall', 'ht', 'seat', 'ticket', 'reg')):
                roll_col = col
            if not name_col and any(k in c_l for k in ('name', 'candidate', 'student')):
                name_col = col
            if not bno_col and 'b no' in c_l:
                bno_col = col
            if not idno_col and 'id no' in c_l:
                idno_col = col

        for _, row in df.iterrows():
            r_val = str(row[roll_col]).strip() if roll_col and pd.notna(row[roll_col]) else ""
            n_val = str(row[name_col]).strip() if name_col and pd.notna(row[name_col]) else ""
            rec = {'roll': r_val, 'name': n_val}
            if bno_col is not None and pd.notna(row[bno_col]):
                rec['bno'] = _roster_cell_str(row[bno_col])
            if idno_col is not None and pd.notna(row[idno_col]):
                # The ID No is written in 3 boxes on the sheet, so a
                # numeric cell (011 stored as 11.0) is zero-padded
                # back to 3 digits.
                rec['idno'] = _roster_cell_str(row[idno_col], pad_digits=3)
            if r_val or n_val:
                records.append(rec)
        if records:
            return records
    except Exception as e:
        print(f"[WARNING] Could not parse roster from {path.name}: {e}")

    return records


def _roster_cell_str(value, pad_digits: int = 0) -> str:
    """A roster cell as a clean string. Pandas reads a numeric cell
    (011) as the float 11.0, so '11.0' is collapsed back to '11';
    pad_digits zero-pads a short all-digit value (the 3-box ID No:
    '11' -> '011'). Non-numeric values pass through unchanged."""
    text = str(value).strip()
    if text.endswith(".0") and text[:-2].isdigit():
        text = text[:-2]
    if pad_digits and text.isdigit() and len(text) < pad_digits:
        text = text.zfill(pad_digits)
    return text


def _best_name_only_match(cand_name: str,
                           roster: List[Dict[str, str]]) -> Tuple[Optional[str], Optional[str]]:
    """Last-resort name-only roster match, below the reconciler's
    0.65 bar. Returns the best record's (roll, name) when its
    no-space name similarity is >= 0.60 AND it beats the second-best
    record by more than 0.05 — a clear winner, not a coin flip.
    PRIYA's name reads 'PRHNA' (0.60 vs PRIYA, 0.50 vs SUPRIYA),
    which the reconciler rejects but this accepts. Returns
    (None, None) when no record is a clear winner.
    """
    from difflib import SequenceMatcher

    def _sim(a: str, b: str) -> float:
        a = re.sub(r"\s+", "", str(a or "").upper())
        b = re.sub(r"\s+", "", str(b or "").upper())
        if not a or not b:
            return 0.0
        return SequenceMatcher(None, a, b).ratio()

    scored = []
    for rec in roster:
        r_roll = str(rec.get("roll", "") or "").strip()
        r_name = str(rec.get("name", "") or "").strip()
        if r_name:
            scored.append((_sim(cand_name, r_name), r_roll, r_name))
    if not scored:
        return (None, None)
    scored.sort(key=lambda s: s[0], reverse=True)
    best_score, best_roll, best_name = scored[0]
    second = scored[1][0] if len(scored) > 1 else 0.0
    if best_score >= 0.60 and best_score - second > 0.05:
        return (best_roll, best_name)
    return (None, None)


def match_daily_test(cand_bno: str, cand_idno: str, cand_name: str,
                     roster: List[Dict[str, str]]) -> Tuple[Optional[str], Optional[str], Optional[str]]:
    """Match a daily-test (20Q) read against a B No / ID No roster.

    Scores each roster record on the three signals the sheet gives:
    B No (batch) 0.40, ID No 0.30, name 0.30 (no-space similarity).
    The best record wins when its score is >= 0.65. The ID No read
    is often partial (thin handwritten '1's are missed), so the B
    No and name carry the match; a wrong B No alone cannot win
    because it is only 0.40 of the score. Returns (bno, idno, name)
    of the winning roster record, or (None, None, None).
    """
    from difflib import SequenceMatcher

    def _sim(a: str, b: str) -> float:
        a = re.sub(r"\s+", "", str(a or "").upper())
        b = re.sub(r"\s+", "", str(b or "").upper())
        if not a or not b:
            return 0.0
        if a == b:
            return 1.0
        return SequenceMatcher(None, a, b).ratio()

    best = None
    best_score = 0.0
    for rec in roster:
        r_bno = str(rec.get("bno", "") or "").strip()
        r_idno = str(rec.get("idno", "") or "").strip()
        r_name = str(rec.get("name", "") or "").strip()
        if not (r_bno or r_idno or r_name):
            continue
        score = 0.40 * _sim(cand_bno, r_bno) + 0.30 * _sim(cand_idno, r_idno) + 0.30 * _sim(cand_name, r_name)
        if score > best_score:
            best_score, best = score, (r_bno, r_idno, r_name)
    if best is not None and best_score >= 0.65:
        return best
    return (None, None, None)


def infer_prefix_from_roster(roster_records: List[Dict[str, str]]) -> Optional[str]:
    """
    Rule 3 (Roster as Prefix Truth):
    Infers the ground-truth exam prefix directly from the imported student nominal roll/roster.
    Extracts the alphanumeric prefix preceding the trailing 3-5 digits across all roster records.
    If a clear dominant prefix is present (>= 30% of records with rolls), returns it.
    """
    if not roster_records:
        return None
    prefixes = []
    for r in roster_records:
        roll = str(r.get("roll", "")).strip().upper()
        if not roll or roll == "NAN":
            continue
        m = re.match(r'^([A-Z0-9]*?[A-Z])\d{3,5}$', roll)
        if m:
            prefixes.append(m.group(1))
    if prefixes:
        counts = Counter(prefixes)
        most_common, cnt = counts.most_common(1)[0]
        if cnt >= max(2, int(len(prefixes) * 0.30)):
            return most_common
    return None


def detect_batch_prefix(image_files: List[Path], engine: OCREngine, sample_limit: int = 15) -> Optional[str]:
    """
    Dynamically infers the shared exam prefix from the scanned sheets in the folder,
    without any hardcoded exam codes. If no shared prefix is detected, returns None.
    """
    prefixes = []
    for fpath in image_files[:sample_limit]:
        try:
            img = cv2.imread(str(fpath))
            if img is None:
                continue
            aligned, angle = Preprocessor.align_and_deskew(img)

            left_marks, right_marks, _ = Preprocessor.detect_timing_tracks(aligned)
            is_200q = (len(left_marks) >= 53 or len(right_marks) >= 53)

            if is_200q:
                ht_raw = aligned[175:222, 515:1115]
            else:
                ht_raw = aligned[218:260, 410:1075]
            z_ht = cv2.resize(ht_raw, None, fx=2.5, fy=2.5, interpolation=cv2.INTER_CUBIC)
            cl_ht = engine.remove_red_color(z_ht)
            h_h, w_h = cl_ht.shape[:2]
            scaled_h = cv2.resize(cl_ht, (int(w_h * 48.0 / h_h), 48), interpolation=cv2.INTER_AREA)
            pad_h = cv2.copyMakeBorder(scaled_h, 12, 12, 25, 25, cv2.BORDER_CONSTANT, value=[255, 255, 255])
            preds_ht, _ = engine.ocr.text_recognizer([pad_h])
            raw_ht = preds_ht[0][0] if preds_ht else ''
            norm = unicodedata.normalize('NFKC', raw_ht)
            clean = re.sub(r'[^A-Za-z0-9]', '', norm).upper()

            # Disambiguate any trailing letters that follow digits at the end
            disambiguated_chars = list(clean)
            for i in range(len(disambiguated_chars) - 1, -1, -1):
                c = disambiguated_chars[i]
                if c.isdigit():
                    break
                elif c in engine.CHAR_TO_DIGIT:
                    disambiguated_chars[i] = engine.CHAR_TO_DIGIT[c]
                else:
                    break
            clean_fixed = "".join(disambiguated_chars)

            m = re.match(r'^([A-Z0-9]*?[A-Z])\d{3,5}$', clean_fixed)
            if m:
                p = m.group(1)
            elif len(clean_fixed) >= 14:
                p = clean_fixed[:10 if is_200q else 11]
            else:
                p = None

            if p:
                if is_200q:
                    p = re.sub(r'K[7T][358S]$', 'KTS', p)
                prefixes.append(p)
        except Exception:
            continue

    if prefixes:
        counts = Counter(prefixes)
        most_common, cnt = counts.most_common(1)[0]
        if cnt >= 2:
            return most_common
    return None


def detect_and_flag_duplicate_hall_tickets(results: List[Dict[str, Any]]) -> Dict[str, List[Dict[str, Any]]]:
    """
    Enforces batch-wide Hall Ticket uniqueness without any hardcoded values.
    Identifies any Hall Ticket number assigned to more than one sheet across the batch,
    and flags all corresponding rows for human review in Excel.

    Args:
        results: List of result dictionaries generated during batch processing.

    Returns:
        Dictionary mapping duplicated Hall Ticket numbers to list of records claiming them.
    """
    ht_groups: Dict[str, List[Dict[str, Any]]] = {}

    for r in results:
        # Only evaluate hall ticket identifications
        if "HALL TICKET" not in str(r.get("Identification Type", "")):
            continue

        ht_val = str(r.get("Hall Ticket / Name", "")).strip().upper()
        # Ignore empty, placeholder, or error records
        if not ht_val or ht_val.startswith("(") or "ERROR" in ht_val or "UNREADABLE" in ht_val:
            continue

        ht_groups.setdefault(ht_val, []).append(r)

    duplicates = {ht: recs for ht, recs in ht_groups.items() if len(recs) > 1}

    for ht, recs in duplicates.items():
        for r in recs:
            r["Status"] = f"REVIEW_REQUIRED (Duplicate HT: {ht})"

    return duplicates


def rank_results(results: List[Dict[str, Any]], has_evaluation: bool = True) -> None:
    """Assigns standard competition ranks (1224 merit-based) in-place."""
    if not has_evaluation or not results:
        return

    def rank_sort_key(r):
        is_err = "ERROR" in str(r.get("Status", "")) or "FAILED" in str(r.get("Status", ""))
        return (
            is_err,
            -float(r.get("Total Marks", 0.0) if isinstance(r.get("Total Marks"), (int, float)) else 0.0),
            -int(r.get("Correct", 0) if isinstance(r.get("Correct"), (int, float)) else 0),
            int(r.get("Wrong", 0) if isinstance(r.get("Wrong"), (int, float)) else 0),
            str(r.get("File Name", ""))
        )

    results.sort(key=rank_sort_key)

    curr_rank = 1
    i = 0
    n = len(results)
    while i < n:
        curr = results[i]
        if "ERROR" in str(curr.get("Status", "")) or "FAILED" in str(curr.get("Status", "")):
            curr["Rank"] = "-"
            i += 1
            continue

        tied = [curr]
        j = i + 1
        while (
            j < n
            and ("ERROR" not in str(results[j].get("Status", "")))
            and ("FAILED" not in str(results[j].get("Status", "")))
            and results[j].get("Total Marks") == curr.get("Total Marks")
        ):
            tied.append(results[j])
            j += 1

        for r in tied:
            r["Rank"] = curr_rank

        curr_rank += len(tied)
        i = j


def export_results_to_excel(
    results: List[Dict[str, Any]],
    output_excel: Optional[Path],
    target_folder: Path,
    has_evaluation: bool = True
) -> Path:
    """Exports structured batch results to a formatted Excel workbook with file lock safety."""
    if has_evaluation:
        col_order = [
            "Rank",
            "File Name",
            "Hall Ticket / Name",
            "B No",
            "ID No",
            "Candidate Name",
            "Identification Type",
            "Reading Mode",
            "Total Marks",
            "Correct",
            "Correct Marks",
            "Wrong",
            "Wrong Marks",
            "Unattempted",
            "Unattempted Marks",
            "Confidence %",
            "Status"
        ]
        sheet_title = "OMR Evaluation & Ranks"
    else:
        for idx, r in enumerate(results, 1):
            r["S.No"] = idx
        col_order = [
            "S.No",
            "File Name",
            "Hall Ticket / Name",
            "B No",
            "ID No",
            "Candidate Name",
            "Identification Type",
            "Reading Mode",
            "Confidence %",
            "Status"
        ]
        sheet_title = "Student Identities"

    # Filter out internal private attributes like _detected_results, _answer_key
    clean_rows = []
    for r in results:
        clean_row = {k: r.get(k, "") for k in col_order}
        clean_rows.append(clean_row)

    df = pd.DataFrame(clean_rows)[col_order]

    if output_excel is None:
        output_excel = target_folder / "OMR_Student_Identities.xlsx"
    else:
        output_excel = Path(output_excel)

    save_path = output_excel
    counter = 1
    thin_border = Border(
        left=Side(style='thin', color='D9D9D9'),
        right=Side(style='thin', color='D9D9D9'),
        top=Side(style='thin', color='D9D9D9'),
        bottom=Side(style='thin', color='D9D9D9')
    )
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    header_fill = PatternFill(start_color="1F4E79", end_color="1F4E79", fill_type="solid")
    review_fill = PatternFill(start_color="FFF2CC", end_color="FFF2CC", fill_type="solid")
    blank_fill = PatternFill(start_color="FCE4D6", end_color="FCE4D6", fill_type="solid")

    while True:
        try:
            with pd.ExcelWriter(save_path, engine="openpyxl") as writer:
                df.to_excel(writer, index=False, sheet_name=sheet_title)
                ws = writer.sheets[sheet_title]
                ws.row_dimensions[1].height = 28

                for col_num in range(1, len(df.columns) + 1):
                    cell = ws.cell(row=1, column=col_num)
                    cell.fill = header_fill
                    cell.font = header_font
                    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

                for row_num in range(2, len(df) + 2):
                    ws.row_dimensions[row_num].height = 20
                    status_col_idx = len(df.columns)
                    status_val = str(ws.cell(row=row_num, column=status_col_idx).value or "")

                    is_blank = "Blank" in status_val or "UNREADABLE" in status_val or "FAILED" in status_val or "ERROR" in status_val
                    is_review = "REVIEW_REQUIRED" in status_val or "MISSING HT" in status_val or "Low Confidence" in status_val
                    is_dup = "Duplicate" in status_val

                    for col_num in range(1, len(df.columns) + 1):
                        cell = ws.cell(row=row_num, column=col_num)
                        col_name = col_order[col_num - 1]
                        cell.font = Font(name="Calibri", size=10)
                        cell.border = thin_border

                        if col_name in ("File Name", "Hall Ticket / Name"):
                            cell.alignment = Alignment(horizontal="left", vertical="center")
                        else:
                            cell.alignment = Alignment(horizontal="center", vertical="center")

                        if col_name in ("Total Marks", "Correct Marks", "Wrong Marks", "Unattempted Marks"):
                            cell.number_format = '0.00'
                        elif col_name == "Confidence %":
                            cell.number_format = '0.0%'

                        if is_blank:
                            cell.fill = blank_fill
                        elif is_review:
                            cell.fill = review_fill

                        if is_dup and col_name == "Status":
                            cell.font = Font(name="Calibri", size=10, bold=True, color="9C0006")

                for col in ws.columns:
                    col_letter = get_column_letter(col[0].column)
                    header_txt = str(col[0].value or "")
                    max_len = max(len(str(cell.value or '')) for cell in col)
                    ws.column_dimensions[col_letter].width = max(max_len + 4, len(header_txt) + 3, 12)
            break
        except PermissionError:
            save_path = target_folder / f"{output_excel.stem}_{counter}{output_excel.suffix}"
            counter += 1

    return save_path


def process_folder(
    target_folder: Path,
    output_excel: Optional[Path] = None,
    exam_prefix: Optional[str] = None,
    key_file: Optional[str] = None,
    roster_file: Optional[str] = None,
    progress_callback: Optional[Any] = None,
    correct_mark: Optional[float] = None,
    wrong_mark: float = 0.00,
    unattempted_mark: float = 0.00,
    from_question: int = 1,
    to_question: Optional[int] = None,
    reading_mode: str = "auto"
):
    """Reading modes (see the app's Reading Mode toggle):
    - "auto": dynamic only when the warped top is cut off, fixed
      otherwise (the behaviour before the toggle existed).
    - "dynamic": always try dynamic first (warped image when the top
      is intact, deskewed copy when it is cut off); fall back to
      fixed when dynamic finds nothing usable.
    - "fixed": never use dynamic; fixed reader + fixed template.
    The mode actually used for each sheet is recorded in the
    "Reading Mode" column of the Excel output.
    """
    mode = (reading_mode or "auto").strip().lower()
    if mode not in ("auto", "dynamic", "fixed"):
        mode = "auto"
    mode_label = {"auto": "Auto", "dynamic": "Dynamic",
                  "fixed": "Fixed"}[mode]

    target_folder = Path(target_folder).resolve()
    if not target_folder.exists() or not target_folder.is_dir():
        err_msg = f"Target directory does not exist: {target_folder}"
        print(f"Error: {err_msg}")
        return False, [], err_msg

    # Find all scanned OMR sheet images (excluding generated crops)
    image_files = sorted([
        f for f in target_folder.iterdir()
        if f.is_file() 
        and f.suffix.lower() in IMAGE_EXTENSIONS
        and not f.stem.endswith("_ht_processed")
        and not f.stem.endswith("_name_processed")
        and not f.stem.endswith("_ht_raw")
        and not f.stem.endswith("_name_raw")
        and not f.name.startswith("debug_")
    ])

    if not image_files:
        err_msg = f"No scanned OMR sheet images found in: {target_folder}"
        print(err_msg)
        return False, [], err_msg

    engine = OCREngine()

    # Check for Student Roster / Nominal Roll file in folder
    roster_path = find_roster_file(target_folder, roster_file)
    roster_records = load_roster(roster_path) if roster_path else None
    roster_rolls = {
        str(r.get("roll", "")).strip().upper() 
        for r in roster_records 
        if r.get("roll") and str(r.get("roll", "")).strip().upper() != "NAN"
    } if roster_records else set()

    # Determine Exam Prefix dynamically (Rule 3: Roster as Prefix Truth)
    batch_scan_pref = detect_batch_prefix(image_files, engine)

    if exam_prefix and exam_prefix.strip():
        active_prefix = exam_prefix.strip()
        prefix_source = "User Specified"
    elif roster_records:
        roster_pref = infer_prefix_from_roster(roster_records)
        # Check if roster prefix matches batch scan prefix:
        # If roster has prefix (e.g. YMG2025SGTS) but batch scans clearly have a different prefix (e.g. KKD2025KTS),
        # the roster is for a different exam! We must NOT force the mismatched roster prefix or records.
        from difflib import SequenceMatcher
        roster_matches_batch = True
        if roster_pref and batch_scan_pref:
            sim = SequenceMatcher(None, roster_pref.upper()[:4], batch_scan_pref.upper()[:4]).ratio()
            if sim < 0.50 and not roster_pref.upper().startswith(batch_scan_pref.upper()[:3]) and not batch_scan_pref.upper().startswith(roster_pref.upper()[:3]):
                roster_matches_batch = False

        if roster_pref and roster_matches_batch:
            active_prefix = roster_pref
            prefix_source = "Inferred from Student Roster"
        elif not roster_matches_batch and batch_scan_pref:
            # Check if roster contains candidate records matching the scanned batch (e.g. KKD2025KTS / RJY2025KTS at the bottom of the roster)
            batch_dist = batch_scan_pref.upper()[:3] if batch_scan_pref else ""
            batch_tail = batch_scan_pref.upper()[-3:] if (batch_scan_pref and len(batch_scan_pref) >= 10) else ""
            filtered_recs = [
                r for r in roster_records
                if (r.get("roll") and (
                    batch_dist in str(r.get("roll")).upper()
                    or (batch_tail and batch_tail in str(r.get("roll")).upper())
                )) or (not r.get("roll") and r.get("name"))
            ]
            if filtered_recs:
                roster_records = filtered_recs
                roster_rolls = {
                    str(r.get("roll", "")).strip().upper()
                    for r in roster_records
                    if r.get("roll") and str(r.get("roll", "")).strip().upper() != "NAN"
                }
                active_prefix = batch_scan_pref
                prefix_source = "Inferred from Scanned Batch & Filtered Student Roster"
                print(f"[INFO] Retained {len(filtered_recs)} candidate records from roster matching batch prefix '{batch_scan_pref}'.")
            else:
                active_prefix = batch_scan_pref
                prefix_source = "Auto-Detected from Batch Scans (Mismatched Roster Ignored)"
                print(f"[WARNING] Roster in folder has prefix '{roster_pref}' which does not match scanned batch prefix '{batch_scan_pref}'. Roster will be ignored to prevent corrupting identities.")
                roster_records = None
                roster_rolls = set()
        elif batch_scan_pref:
            active_prefix = batch_scan_pref
            prefix_source = "Auto-Detected from Batch Scans"
        else:
            active_prefix = roster_pref
            prefix_source = "Inferred from Student Roster" if active_prefix else "Dynamic OCR"
    else:
        active_prefix = batch_scan_pref
        prefix_source = "Auto-Detected from Batch Scans" if active_prefix else "Dynamic OCR (No Shared Prefix)"

    # Check for Answer Key PDF in folder
    key_pdf_path = find_answer_key_pdf(target_folder, key_file)
    answer_key = None
    has_evaluation = False

    if key_pdf_path:
        try:
            extractor = AnswerKeyExtractor()
            extracted_key = extractor.extract_from_pdf(key_pdf_path)
            if extracted_key and len(extracted_key.items) > 0:
                answer_key = extracted_key
                has_evaluation = True
        except Exception as e:
            print(f"[WARNING] Failed to parse Answer Key from {key_pdf_path.name}: {e}")
            answer_key = None
            has_evaluation = False

    num_questions = len(answer_key.items) if has_evaluation else 0
    if not has_evaluation:
        # Check first scan timing marks to see if it's 200Q or 160Q
        try:
            sample_img = cv2.imread(str(image_files[0]))
            if sample_img is not None:
                sm_l, sm_r, _ = Preprocessor.detect_timing_tracks(sample_img)
                if len(sm_l) >= 53:
                    num_questions = 200
                else:
                    num_questions = 160
            else:
                num_questions = 160
        except Exception:
            num_questions = 160

    template = get_template(num_questions)

    # Dynamic Scoring Configuration:
    if correct_mark is not None:
        active_correct_mark = float(correct_mark)
    elif num_questions == 160:
        active_correct_mark = 0.50
    else:
        active_correct_mark = 1.00

    active_wrong_mark = float(wrong_mark)
    active_unattempted_mark = float(unattempted_mark)
    active_from_q = max(1, from_question)
    active_to_q = min(num_questions, to_question) if to_question else num_questions

    bubble_detector = BubbleDetector(template=template) if has_evaluation else None
    scoring_engine = ScoringEngine(
        correct_mark=active_correct_mark,
        wrong_mark=active_wrong_mark,
        unattempted_mark=active_unattempted_mark,
        total_questions=num_questions if num_questions > 0 else template.total_questions,
        from_question=active_from_q,
        to_question=active_to_q
    ) if has_evaluation else None

    print("=" * 96)
    print("OFFLINE OMR BATCH EVALUATION & IDENTITY EXTRACTION")
    print(f"Target Directory     : {target_folder}")
    print(f"Scanned Images Found : {len(image_files)}")
    if active_prefix:
        print(f"Exam Prefix          : {active_prefix} ({prefix_source})")
    else:
        print(f"Exam Prefix          : {prefix_source}")
    print(f"Reading Mode         : {mode_label}")

    if roster_records:
        print(f"Student Roster File  : {roster_path.name} ({len(roster_records)} Candidates Loaded - 99%+ Match Mode)")
    else:
        print("Student Roster File  : None Detected (Dynamic OCR Mode)")

    if has_evaluation:
        print(f"Answer Key File      : {key_pdf_path.name} ({num_questions} Questions Loaded)")
        print(f"Scoring Scheme       : Correct: {active_correct_mark:+.2f} | Wrong: {active_wrong_mark:+.2f} | Unattempted: {active_unattempted_mark:+.2f}")
        print(f"Evaluation Scope     : Questions {active_from_q} to {active_to_q} (Template: {template.name})")
        print("Evaluation Mode      : FULL (Identities + OMR Marks + Competition Ranking)")
    else:
        print("Answer Key File      : None Detected (Identity-Only Mode)")
        print("                       (To evaluate marks and ranks, place answer key .pdf in this folder)")
    print("=" * 96)

    results = []

    start_time = time.time()
    for idx, fpath in enumerate(image_files, 1):
        print(f"[{idx:02d}/{len(image_files):02d}] Processing: {fpath.name:<22}", end=" ... ", flush=True)

        try:
            img = cv2.imread(str(fpath))
            if img is None:
                print("FAILED (Corrupt or unreadable image)")
                err_record = {
                    "File Name": fpath.name,
                    "Hall Ticket / Name": "UNREADABLE IMAGE",
                    "Identification Type": "ERROR",
                    "Reading Mode": mode_label,
                    "Confidence %": 0.0,
                    "Status": "FAILED"
                }
                if has_evaluation:
                    err_record.update({
                        "Total Marks": 0.0,
                        "Correct": 0,
                        "Correct Marks": 0.0,
                        "Wrong": 0,
                        "Wrong Marks": 0.0,
                        "Unattempted": 0,
                        "Unattempted Marks": 0.0,
                    })
                results.append(err_record)
                continue

            # 1. Timing track alignment & deskew
            left_marks, right_marks, angle = Preprocessor.detect_timing_tracks(img)
            aligned, angle = Preprocessor.align_and_deskew(img)
            is_200q = (len(left_marks) >= 53 or len(right_marks) >= 53)

            # Dynamic path selection (Reading Mode toggle):
            # - auto: dynamic only when the warped top is cut off
            #   (200Q Syam sheet): the hall-ticket row maps above
            #   y=0, so the fixed reader below crops the Instructions
            #   box instead of the hall-ticket boxes. A box row
            #   touching the top edge of the warped image means the
            #   top is cut off, so read the deskewed-only copy
            #   (whole page in frame) with dynamic detection instead.
            #   When the top is intact, the fixed reader below runs
            #   exactly as before.
            #   Auto also uses dynamic when no fixed template exists
            #   for the question count (templates cover exactly 160Q
            #   and 200Q): a 150Q sheet run through the fixed reader
            #   would get the 160Q template and read garbage.
            # - dynamic: always try dynamic first — on the warped
            #   image when the top is intact, on the deskewed copy
            #   when it is cut off. Falls back to fixed below when
            #   dynamic finds nothing usable.
            # - fixed: never use dynamic.
            dyn = None
            use_dynamic = False
            dyn_image = aligned
            try:
                from app.omr.dynamic import (
                    analyze_sheet_dynamic, dynamic_rows_to_detected,
                    extract_identity_20q, identity_crops, top_is_cut_off,
                )
                top_cut = top_is_cut_off(aligned)
                no_fixed_template = num_questions not in (160, 200)
                want_dynamic = (mode == "dynamic"
                                or (mode == "auto"
                                    and (top_cut or no_fixed_template)))
                if want_dynamic:
                    # No timing track on the raw sheet (the 20Q strip
                    # and the 50Q photo have no timing marks at all):
                    # the warp to the 160Q reference points distorts
                    # them, so read the deskewed-only copy instead
                    # (original size, rotation only).
                    no_track = (len(left_marks) < 2
                                and len(right_marks) < 2)
                    if top_cut or no_track:
                        dyn_image = Preprocessor.deskew_only(img)[0]
                    dyn = analyze_sheet_dynamic(
                        dyn_image, expected_questions=num_questions,
                        ocr_engine=engine,
                        exam_prefix=active_prefix or None)
                    use_dynamic = (dyn.method == "dynamic"
                                   and dyn.found_questions >= 1)
            except Exception:
                dyn = None
                use_dynamic = False

            # 2. Extract Student Identity (HT / Name)
            b_no = ""
            id_no = ""
            if use_dynamic:
                ht = dyn.identity.hall_ticket or ""
                name = dyn.identity.name or ""
                conf = dyn.identity.confidence
                valid = bool(ht and re.match(r"^[A-Z0-9]{4,20}$", ht))
                crops = identity_crops(dyn_image, dyn.identity, engine)
                # Daily-test (20Q) strip: no hall-ticket box row — the
                # identity is B No / ID No / name from the small table
                # at the top right. The fixed reader cannot read it
                # (its 160Q/200Q strips land on the wrong place), so
                # the 20Q reader + roster match replaces the vote.
                is_daily = bool(roster_records) and any(
                    "bno" in r for r in roster_records)
                if not is_daily and not ht and not name and num_questions is not None and num_questions <= 25:
                    is_daily = True
                if is_daily:
                    try:
                        daily = extract_identity_20q(dyn_image, engine)
                        matched = (None, None, None)
                        if roster_records:
                            for b_cand in daily.b_no_candidates or [""]:
                                for i_cand in daily.id_no_candidates or [""]:
                                    for n_cand in daily.name_candidates or [daily.name]:
                                        matched = match_daily_test(
                                            b_cand, i_cand, n_cand, roster_records)
                                        if matched[0] or matched[2]:
                                            break
                                    if matched[0] or matched[2]:
                                        break
                                if matched[0] or matched[2]:
                                    break
                        if matched[0] or matched[2]:
                            b_no, id_no, name = matched
                            ht = ""
                            conf = 0.9
                            valid = True
                        else:
                            # No roster match: keep the best raw read.
                            b_no = daily.b_no or ""
                            id_no = daily.id_no or ""
                            name = daily.name or ""
                            conf = 0.7 if (b_no or id_no or name) else 0.0
                            valid = bool(b_no or id_no or name)
                    except Exception:
                        pass
                if not b_no and not id_no:
                    # Both readers vote: the fixed reader runs on the same
                    # sheet, and when the two readings disagree the roster
                    # decides (348819: dynamic read 'KKD2025K7300694',
                    # fixed read 'KKD2025KTS00627'; the roster picks the
                    # fixed reading, 'KKD2025KTS01627'). Without a roster,
                    # or when neither reading matches a roster student, the
                    # dynamic reading stands.
                    try:
                        f_ht, f_name, f_conf, _f_valid, f_crops = engine.extract_identity(
                            aligned, exam_prefix=active_prefix, roster=None,
                            return_crops=True, is_200q=is_200q)
                        v_ht, v_name, v_source = engine.resolve_identity_vote(
                            ht, name, f_ht, f_name,
                            roster=roster_records or None,
                            preferred_prefix=active_prefix)
                        if v_source == "fixed":
                            ht, name, conf, valid, crops = (
                                v_ht, v_name, f_conf,
                                bool(v_ht and re.match(r"^[A-Z0-9]{4,20}$", v_ht)),
                                f_crops)
                        else:
                            ht, name = v_ht, v_name
                            valid = bool(ht and re.match(r"^[A-Z0-9]{4,20}$", ht))
                    except Exception:
                        # The vote must never break a working dynamic read.
                        pass
                    # Alternate name readings: when the primary name did
                    # not reconcile to a roster student, try the other
                    # cleanings of the same strip (ink-binary reads
                    # PRIYA's name as 'PRIVA', 0.8 similar, where the
                    # red-drop 'PRHNA' scores only 0.6 and fails).
                    # Each candidate is tried with the hall ticket and
                    # without it: a garbled HT with digits (SUPRIYA's
                    # 'SUTTATRS440') poisons the dual-signal match, so
                    # the name-only path is the fallback that resolves
                    # her ('SOPRIA' -> T11-490) and VENKATARAMANA.
                    if (roster_records and dyn.identity.name_candidates):
                        try:
                            r_ht, _r_name = engine._reconcile_with_roster(
                                ht, name, ht, roster_records)
                            if not r_ht:
                                found = False
                                for cand in dyn.identity.name_candidates:
                                    for try_ht in (ht, ""):
                                        r_ht2, r_name2 = engine._reconcile_with_roster(
                                            try_ht, cand, try_ht, roster_records)
                                        if r_ht2:
                                            ht, name = r_ht2, r_name2
                                            valid = bool(ht and re.match(r"^[A-Z0-9]{4,20}$", ht))
                                            found = True
                                            break
                                    if found:
                                        break
                                if not found:
                                    # Last resort: a clear-winner
                                    # name-only match below the
                                    # reconciler's bar (PRIYA).
                                    for cand in dyn.identity.name_candidates:
                                        r_ht3, r_name3 = _best_name_only_match(
                                            cand, roster_records)
                                        if r_ht3:
                                            ht, name = r_ht3, r_name3
                                            valid = bool(ht and re.match(r"^[A-Z0-9]{4,20}$", ht))
                                            break
                        except Exception:
                            pass
                if not ht and not name and not b_no and not id_no:
                    # Dynamic found nothing usable: fall back to the
                    # fixed reader below.
                    use_dynamic = False
            if not use_dynamic:
                ht, name, conf, valid, crops = engine.extract_identity(
                    aligned, exam_prefix=active_prefix, roster=roster_records, return_crops=True, is_200q=is_200q
                )

            # Save cropped debug images
            ht_crop_file = target_folder / f"{fpath.stem}_ht_processed.png"
            name_crop_file = target_folder / f"{fpath.stem}_name_processed.png"
            cv2.imwrite(str(ht_crop_file), crops["ht_processed"])
            cv2.imwrite(str(name_crop_file), crops["name_processed"])

            crops_dir = target_folder / "processed_crops"
            crops_dir.mkdir(exist_ok=True)
            cv2.imwrite(str(crops_dir / f"{fpath.stem}_ht_processed.png"), crops["ht_processed"])
            cv2.imwrite(str(crops_dir / f"{fpath.stem}_name_processed.png"), crops["name_processed"])
            cv2.imwrite(str(crops_dir / f"{fpath.stem}_ht_raw.png"), crops["ht_raw"])
            cv2.imwrite(str(crops_dir / f"{fpath.stem}_name_raw.png"), crops["name_raw"])

            # 3. OMR Bubble Evaluation (if key PDF present)
            correct_cnt = 0
            correct_marks = 0.0
            wrong_cnt = 0
            wrong_marks = 0.0
            unattempted_cnt = 0
            unattempted_marks = 0.0
            total_marks = 0.0
            detected_results = {}

            if has_evaluation:
                if use_dynamic:
                    # Same dynamic bubble grid as EvaluationService, on
                    # the deskewed copy — the fixed template misreads
                    # this sheet badly (69 unattempted on the old run).
                    detected_results = dynamic_rows_to_detected(dyn)
                else:
                    ink_map = Preprocessor.extract_ink_channel(aligned)
                    detected_results = bubble_detector.analyze_sheet(
                        ink_map,
                        timing_marks=(left_marks, right_marks),
                        image_bgr=aligned
                    )
                _, correct_cnt, wrong_cnt, unattempted_cnt, total_marks, _, _ = scoring_engine.evaluate_sheet(
                    detected_results, answer_key.items
                )
                correct_marks = round(correct_cnt * active_correct_mark, 2)
                wrong_marks = round(wrong_cnt * active_wrong_mark, 2)
                unattempted_marks = round(unattempted_cnt * active_unattempted_mark, 2)

            # 4. Determine Display Identity and Status
            ht_missing_on_sheet = crops.get("ht_missing_on_sheet", False)

            if b_no or id_no:
                # Daily-test (20Q) strip: the identity is B No / ID
                # No / name — there is no hall ticket to miss.
                identity_val = name if name else "(BLANK / UNREADABLE)"
                id_type = "B NO / ID NO"
                if name and (b_no or id_no):
                    status = "SUCCESS"
                else:
                    status = "REVIEW_REQUIRED (Missing B No / ID No)"
                disp_msg = f"B No: {b_no or '-'} ID No: {id_no or '-'} Name: {identity_val} ({conf*100:.1f}%)"
            elif ht:
                if ht_missing_on_sheet:
                    # Rule 2: Assigned by Candidate Name match against Roster
                    identity_val = ht
                    id_type = "HALL TICKET (ASSIGNED BY NAME)"
                    status = "REVIEW_REQUIRED (Assigned by Name - Verify)"
                    disp_msg = f"ASSIGNED BY NAME -> HT: {ht} ({conf*100:.1f}%)"
                else:
                    # Physically written Hall Ticket
                    identity_val = ht
                    id_type = "HALL TICKET"
                    if conf < 0.60:
                        status = "REVIEW_REQUIRED (Low Confidence)"
                    elif roster_rolls and ht.upper() not in roster_rolls:
                        # Rule 1: Roster Membership Gatekeeper
                        status = "REVIEW_REQUIRED (Unregistered HT / Mismatch)"
                    else:
                        status = "SUCCESS"
                    disp_msg = f"HT: {ht} ({conf*100:.1f}%)"
            else:
                identity_val = name if name else "(BLANK / UNREADABLE)"
                id_type = "CANDIDATE NAME (MISSING HT)"
                if not name and (not has_evaluation or unattempted_cnt >= 155):
                    status = "REVIEW_REQUIRED (Blank Sheet)"
                else:
                    status = "REVIEW_REQUIRED (Missing HT)"
                disp_msg = f"MISSING HT -> NAME: {identity_val} ({conf*100:.1f}%)"

            if has_evaluation and unattempted_cnt == num_questions:
                status = "REVIEW_REQUIRED (Blank / Unattempted)"

            if has_evaluation:
                print(f"{disp_msg:<40} | Marks: {total_marks:5.2f} (C:{correct_cnt:3d} W:{wrong_cnt:3d} U:{unattempted_cnt:3d})")
            else:
                print(disp_msg)

            record = {
                "File Name": fpath.name,
                "Hall Ticket / Name": identity_val,
                "B No": b_no,
                "ID No": id_no,
                "Candidate Name": name if name else "",
                "_detected_name": name if name else "",
                "Identification Type": id_type,
                "Reading Mode": "Dynamic" if use_dynamic else "Fixed",
                "Confidence %": round(conf, 4),
                "Status": status,
                "_detected_results": detected_results,
                "_answer_key": answer_key.items if answer_key else {},
                "_total_questions": num_questions
            }

            if has_evaluation:
                record.update({
                    "Total Marks": float(total_marks),
                    "Correct": int(correct_cnt),
                    "Correct Marks": float(correct_marks),
                    "Wrong": int(wrong_cnt),
                    "Wrong Marks": float(wrong_marks),
                    "Unattempted": int(unattempted_cnt),
                    "Unattempted Marks": float(unattempted_marks),
                })

            results.append(record)
            if progress_callback:
                try:
                    progress_callback(idx, len(image_files), fpath.name, disp_msg)
                except Exception:
                    pass

        except Exception as e:
            print(f"ERROR ({str(e)})")
            err_record = {
                "File Name": fpath.name,
                "Hall Ticket / Name": "ERROR",
                "Identification Type": "EXCEPTION",
                "Reading Mode": mode_label,
                "Confidence %": 0.0,
                "Status": f"ERROR: {str(e)}",
                "_detected_results": {},
                "_answer_key": answer_key.items if answer_key else {},
                "_total_questions": num_questions
            }
            if has_evaluation:
                err_record.update({
                    "Total Marks": 0.0,
                    "Correct": 0,
                    "Correct Marks": 0.0,
                    "Wrong": 0,
                    "Wrong Marks": 0.0,
                    "Unattempted": 0,
                    "Unattempted Marks": 0.0,
                })
            results.append(err_record)
            if progress_callback:
                try:
                    progress_callback(idx, len(image_files), fpath.name, f"ERROR: {str(e)}")
                except Exception:
                    pass

    elapsed = time.time() - start_time
    print("=" * 96)
    print(f"Processed {len(image_files)} sheets in {elapsed:.2f} seconds ({elapsed/len(image_files):.2f}s per sheet)")

    # Batch-wide Duplicate Hall Ticket Validation & Flagging (100% Dynamic)
    duplicate_hts = detect_and_flag_duplicate_hall_tickets(results)
    if duplicate_hts:
        total_dup_sheets = sum(len(recs) for recs in duplicate_hts.values())
        print(f"\n[WARNING] Duplicate Hall Ticket numbers detected in batch ({len(duplicate_hts)} unique HTs across {total_dup_sheets} sheets):")
        for dup_ht, recs in sorted(duplicate_hts.items()):
            sharing_files = [r.get("File Name", "") for r in recs]
            print(f"  --> Duplicate HT '{dup_ht}' claimed by {len(recs)} sheets: {', '.join(sharing_files)}")
        print(f"  ==> All {total_dup_sheets} sheets flagged with 'REVIEW_REQUIRED (Duplicate HT)' in Excel.\n")

    # Competition Ranking (1224) if evaluation active
    if has_evaluation:
        rank_results(results, has_evaluation=True)
        top_score = results[0]["Total Marks"] if results else 0.0
        avg_score = sum(r["Total Marks"] for r in results if isinstance(r.get("Total Marks"), (int, float))) / max(len(results), 1)
        print(f"Evaluation Summary   : Top Score: {top_score:.2f} Marks | Class Average: {avg_score:.2f} Marks")

    success_count = sum(1 for r in results if r["Status"] == "SUCCESS")
    review_count = len(results) - success_count
    if duplicate_hts:
        total_dup_sheets = sum(len(recs) for recs in duplicate_hts.values())
